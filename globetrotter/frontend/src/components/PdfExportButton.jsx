function formatICSDate(dateStr, timeStr = '09:00') {
  // dateStr = "2026-09-10", timeStr = "09:00 AM"
  const d = new Date(dateStr);
  const year = d.getFullYear();
  const month = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');

  // Parse time
  let hours = 9;
  let minutes = 0;
  if (timeStr) {
    const match = timeStr.match(/(\d+):(\d+)\s*(AM|PM)?/i);
    if (match) {
      hours = parseInt(match[1]);
      minutes = parseInt(match[2]);
      if (match[3] && match[3].toUpperCase() === 'PM' && hours < 12) hours += 12;
      if (match[3] && match[3].toUpperCase() === 'AM' && hours === 12) hours = 0;
    }
  }
  const h = String(hours).padStart(2, '0');
  const m = String(minutes).padStart(2, '0');
  return `${year}${month}${day}T${h}${m}00`;
}

function generateICS(generatedPlan, travelerName) {
  const lines = [
    'BEGIN:VCALENDAR',
    'VERSION:2.0',
    'PRODID:-//GlobeTrotter//TripPlanner//EN',
    'CALSCALE:GREGORIAN',
    'METHOD:PUBLISH',
    `X-WR-CALNAME:${generatedPlan.destination?.name || 'My Trip'} — GlobeTrotter`,
    `X-WR-TIMEZONE:Asia/Kolkata`,
  ];

  const tripStartDate = generatedPlan.travelDates?.start || new Date().toISOString().split('T')[0];

  generatedPlan.days.forEach((day) => {
    const dayDate = new Date(tripStartDate);
    dayDate.setDate(dayDate.getDate() + (day.dayNumber - 1));
    const dateStr = dayDate.toISOString().split('T')[0];

    day.activities.forEach((act) => {
      const startTime = act.timeRange ? act.timeRange.split(' - ')[0] : '09:00';
      const endTime = act.timeRange ? act.timeRange.split(' - ')[1] : '11:00';
      const dtStart = formatICSDate(dateStr, startTime);
      const dtEnd = formatICSDate(dateStr, endTime);
      const uid = `gt-${act.id || Math.random().toString(36).substr(2, 9)}@globetrotter`;

      const description = [
        act.description || '',
        act.cost === 0 ? 'Free Entry' : `Entry Fee: ₹${act.cost}`,
        act.transitDetail ? `How to Reach: ${act.transitDetail}` : '',
        act.insiderTip ? `Tip: ${act.insiderTip}` : '',
        '',
        'Generated by GlobeTrotter AI Trip Planner',
      ].filter(Boolean).join('\\n');

      lines.push('BEGIN:VEVENT');
      lines.push(`UID:${uid}`);
      lines.push(`DTSTART:${dtStart}`);
      lines.push(`DTEND:${dtEnd}`);
      lines.push(`SUMMARY:${act.name} (Day ${day.dayNumber})`);
      lines.push(`DESCRIPTION:${description}`);
      lines.push(`CATEGORIES:${act.category || 'Tourism'}`);
      lines.push(`STATUS:CONFIRMED`);
      lines.push('END:VEVENT');
    });
  });

  lines.push('END:VCALENDAR');
  return lines.join('\r\n');
}

function triggerICSDownload(icsContent, fileName) {
  const blob = new Blob([icsContent], { type: 'text/calendar;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = fileName;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

