function generateWhatsAppText(generatedPlan) {
  const dest = generatedPlan.destination?.name || 'Trip';
  const lines = [
    `🌍 *GlobeTrotter Itinerary — ${dest}*`,
    `📅 ${generatedPlan.travelDates?.start || generatedPlan.startDate || ''} → ${generatedPlan.travelDates?.end || generatedPlan.endDate || ''}`,
    `⏱️ ${generatedPlan.totalDays} Days | 💰 Est. ₹${(generatedPlan.totalEstimatedCost || generatedPlan.estimatedBudget || 0).toLocaleString()}`,
    ''
  ];
  (generatedPlan.days || []).forEach(day => {
    lines.push(`*📅 Day ${day.dayNumber}: ${day.themeTitle || 'Day ' + day.dayNumber}*`);
    (day.activities || []).forEach(act => {
      lines.push(`  • ${act.name} (${act.slot || 'Morning'}) — ${act.cost === 0 ? 'Free' : '₹' + act.cost}`);
      if (act.insiderTip) lines.push(`    💡 Tip: ${act.insiderTip}`);
    });
    if (day.suggestedMeals) {
      lines.push(`  🍽️ Dining: ${day.suggestedMeals.lunch || ''} • ${day.suggestedMeals.dinner || ''}`);
    }
    lines.push('');
  });
  lines.push('Generated by GlobeTrotter AI Trip Planner 🚀');
  lines.push('https://globetrotter.app');
  return lines.join('\n');
}

